@dataclass(frozen=True)
class ProgrammaticToolCall:
    call_id: str
    tool_name: str
    arguments: dict[str, Any]
    caller_program_id: str | None = None


@dataclass
class ProgrammaticExecutionState:
    task_id: str
    program_id: str | None = None
    program_code: str = ""
    tool_calls_executed: int = 0
    max_tool_calls: int = 50
    changed_files: list[str] = field(default_factory=list)
    commands_run: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    total_tokens: dict[str, int] = field(default_factory=dict)
    verification_results: list[dict[str, Any]] = field(default_factory=list)
    active: bool = True


class ToolExecutionDispatcher:
    """Dispatches tool calls generated by JS programs to registered local Mana tools."""

    def __init__(
        self,
        workspace: WorkspaceContext | None = None,
        *,
        repo_root: str | FilePath | None = None,
        extra_tools: dict[str, Callable[..., Any]] | None = None,
        task_id: str = "",
        model: str = "",
        provider: str = "openai",
    ) -> None:
        if workspace is not None:
            self.workspace = workspace
            self.repo_root = FilePath(getattr(workspace, "worktree_path", None) or getattr(workspace, "repo_root", ".") or ".").resolve()
        else:
            resolved_path = FilePath(repo_root or ".").resolve()
            self.workspace = WorkspaceContext(
                repository_path=resolved_path,
                worktree_path=resolved_path,
                allow_in_place_write=True,
            )
            self.repo_root = resolved_path
        self.extra_tools = extra_tools or {}
        self.task_id = task_id
        self.model = model
        self.provider = provider

    def is_tool_allowed(self, tool_name: str) -> bool:
        tool_name = re.sub(r"[^a-zA-Z0-9_-]", "_", tool_name)
        write_tools = {
            "run_command", "run_script_once", "shell",
            "write_file",
            "create_file",
            "edit_file",
            "multi_edit_file",
            "delete_file",
            "apply_patch",
            "apply_patch_batch",
            "batch_write_files",
            "batch_apply_patches",
            "batch_move_files",
            "batch_delete_files",
        }
        if self.workspace.sandbox == "readOnly" and tool_name in write_tools:
            return False
        return True

    def dispatch(self, tool_name: str, arguments: dict[str, Any], *, call_id: str = "") -> dict[str, Any]:
        """Execute a tool locally and return a JSON-serializable dict."""
        if not self.is_tool_allowed(tool_name):
            return {
                "ok": False,
                "error": f"Tool '{tool_name}' cannot be executed in a readOnly sandbox.",
                "error_code": "SANDBOX_VIOLATION",
            }

        tool_name = str(tool_name or "").strip()
        normalized = re.sub(r"[^a-zA-Z0-9_-]", "_", tool_name)

        # Check for extra custom or MCP tools first (supports both exact and normalized keys)
        for cand in (tool_name, normalized, tool_name.replace("_", ".")):
            if cand in self.extra_tools:
                try:
                    res = self.extra_tools[cand](**arguments)
                    if isinstance(res, dict):
                        return res
                    return {"ok": True, "result": res}
                except Exception as exc:
                    return {"ok": False, "error": str(exc), "error_code": "TOOL_EXECUTION_ERROR"}

        # Native tool implementations
        try:
            native_arguments = dict(arguments)
            if normalized in {"shell", "run_command", "run_script_once"}:
                native_arguments["_mana_call_id"] = call_id or uuid.uuid4().hex
            return self._execute_builtin_tool(tool_name, native_arguments)
        except Exception as exc:
            logger.exception("Error executing builtin tool %s", tool_name)
            return {"ok": False, "error": str(exc), "error_code": "TOOL_EXECUTION_ERROR"}

    def execute_tool(self, tool_name: str, arguments: dict[str, Any]) -> dict[str, Any]:
        """Execute a tool locally and return a JSON-serializable dict (alias for dispatch)."""
        return self.dispatch(tool_name, arguments)

    def _execute_builtin_tool(self, tool_name: str, args: dict[str, Any]) -> dict[str, Any]:
        from mana_agent.tools.apply_patch import safe_apply_patch
        from mana_agent.tools.edit_file import safe_edit_file, safe_multi_edit_file
        from mana_agent.tools.repository import (
            apply_patch_batch,
            call_graph,
            find_symbols,
            git_diff,
            git_status,
            list_files,
            repo_batch_read,
            repo_batch_search,
            repo_search,
            run_script_once,
            verify_project,
        )
        from mana_agent.tools.write_file import safe_create_file, safe_delete_file, safe_write_file

        name = re.sub(r"[^a-zA-Z0-9_-]", "_", tool_name)

        if name == "read_file":
            rel_path = str(args.get("path") or args.get("file_path") or "").strip()
            target = (self.repo_root / rel_path).resolve()
            if not target.is_relative_to(self.repo_root) or not target.is_file():
                return {"ok": False, "error": f"File not found or outside workspace: {rel_path}"}
            start_line = args.get("start_line")
            end_line = args.get("end_line")
            text = target.read_text(encoding="utf-8", errors="replace")
            lines = text.splitlines(keepends=True)
            total_lines = len(lines)
            if start_line is not None or end_line is not None:
                s = max(1, int(start_line or 1))
                e = min(total_lines, int(end_line or total_lines))
                sliced = "".join(lines[s - 1 : e])
                return {"ok": True, "path": rel_path, "content": sliced, "start_line": s, "end_line": e, "total_lines": total_lines}
            return {"ok": True, "path": rel_path, "content": text, "total_lines": total_lines}

        elif name == "read_skill":
            from mana_agent.skills.manager import read_skill
            skill_name = str(args.get("skill_name") or args.get("name") or "")
            try:
                content = read_skill(skill_name, project_root=self.repo_root)
                return {"ok": True, "content": content}
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "SKILL_READ_FAILED"}

        elif name == "list_files":
            glob = str(args.get("glob") or args.get("pattern") or "**/*")
            limit = int(args.get("limit") or 200)
            res = list_files(self.repo_root, glob=glob, limit=limit)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "repo_search":
            query = str(args.get("query") or "")
            glob = str(args.get("glob") or "**/*")
            regex = bool(args.get("regex", False))
            limit = int(args.get("limit") or 100)
            res = repo_search(self.repo_root, query=query, glob=glob, regex=regex, limit=limit)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "repo_batch_read":
            files = list(args.get("files") or [])
            res = repo_batch_read(self.repo_root, files=files)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "repo_batch_search":
            patterns = list(args.get("patterns") or [])
            res = repo_batch_search(self.repo_root, patterns=patterns)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "find_symbols":
            query = str(args.get("query") or "")
            limit = int(args.get("limit") or 100)
            res = find_symbols(self.repo_root, query=query, limit=limit)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "call_graph":
            query = str(args.get("query") or "")
            limit = int(args.get("limit") or 100)
            res = call_graph(self.repo_root, query=query, limit=limit)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "write_file":
            path = str(args.get("path") or "")
            content = str(args.get("content") or "")
            res = safe_write_file(repo_root=self.repo_root, path=path, content=content, force=bool(args.get("force", True)))
            return res.to_dict() if hasattr(res, "to_dict") else res

        elif name == "create_file":
            path = str(args.get("path") or "")
            content = str(args.get("content") or "")
            res = safe_create_file(repo_root=self.repo_root, path=path, content=content)
            return res.to_dict() if hasattr(res, "to_dict") else res

        elif name == "delete_file":
            path = str(args.get("path") or "")
            res = safe_delete_file(repo_root=self.repo_root, path=path)
            return res.to_dict() if hasattr(res, "to_dict") else res

        elif name == "edit_file":
            path = str(args.get("path") or "")
            old_str = str(args.get("old_string") or "")
            new_str = str(args.get("new_string") or "")
            replace_all = bool(args.get("replace_all", False))
            res = safe_edit_file(repo_root=self.repo_root, path=path, old_string=old_str, new_string=new_str, replace_all=replace_all)
            return res.to_dict() if hasattr(res, "to_dict") else res

        elif name == "multi_edit_file":
            path = str(args.get("path") or "")
            edits = list(args.get("edits") or [])
            res = safe_multi_edit_file(repo_root=self.repo_root, path=path, edits=edits)
            return res.to_dict() if hasattr(res, "to_dict") else res

        elif name == "apply_patch":
            patch = str(args.get("patch") or "")
            res = safe_apply_patch(repo_root=self.repo_root, patch=patch)
            return res.to_dict() if hasattr(res, "to_dict") else res

        elif name == "apply_patch_batch":
            patches = list(args.get("patches") or [])
            res = apply_patch_batch(self.repo_root, patches=patches)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "batch_read_files":
            from mana_agent.tools.batch_file_ops import batch_read_files
            files = list(args.get("files") or [])
            max_bytes = int(args.get("max_bytes") or 2_000_000)
            max_bytes_per_file = int(args.get("max_bytes_per_file") or 150_000)
            concurrency = int(args.get("concurrency") or 8)
            return batch_read_files(
                self.repo_root,
                files=files,
                max_bytes=max_bytes,
                max_bytes_per_file=max_bytes_per_file,
                concurrency=concurrency,
            )

        elif name == "batch_write_files":
            from mana_agent.tools.batch_file_ops import batch_write_files
            writes = list(args.get("writes") or [])
            rollback = bool(args.get("rollback_on_failure", True))
            check_only = bool(args.get("check_only", False))
            return batch_write_files(
                self.repo_root,
                writes=writes,
                rollback_on_failure=rollback,
                check_only=check_only,
            )

        elif name == "batch_apply_patches":
            from mana_agent.tools.batch_file_ops import batch_apply_patches
            patches = list(args.get("patches") or [])
            rollback = bool(args.get("rollback_on_failure", True))
            check_only = bool(args.get("check_only", False))
            return batch_apply_patches(
                self.repo_root,
                patches=patches,
                rollback_on_failure=rollback,
                check_only=check_only,
            )

        elif name == "batch_search_files":
            from mana_agent.tools.batch_file_ops import batch_search_files
            patterns = list(args.get("patterns") or [])
            concurrency = int(args.get("concurrency") or 4)
            return batch_search_files(
                self.repo_root,
                patterns=patterns,
                concurrency=concurrency,
            )

        elif name == "batch_list_files":
            from mana_agent.tools.batch_file_ops import batch_list_files
            queries = list(args.get("queries") or [])
            limit = int(args.get("limit") or 200)
            return batch_list_files(
                self.repo_root,
                queries=queries,
                limit=limit,
            )

        elif name == "batch_move_files":
            from mana_agent.tools.batch_file_ops import batch_move_files
            moves = list(args.get("moves") or [])
            rollback = bool(args.get("rollback_on_failure", True))
            return batch_move_files(
                self.repo_root,
                moves=moves,
                rollback_on_failure=rollback,
            )

        elif name == "batch_delete_files":
            from mana_agent.tools.batch_file_ops import batch_delete_files
            paths = list(args.get("paths") or [])
            rollback = bool(args.get("rollback_on_failure", True))
            return batch_delete_files(
                self.repo_root,
                paths=paths,
                rollback_on_failure=rollback,
            )

        elif name in {"run_command", "run_script_once", "shell"}:
            cmd = str(args.get("command") or args.get("script") or args.get("cmd") or "")
            cwd = args.get("cwd")
            timeout_s = int(args.get("timeout") or (int(args["timeout_ms"]) // 1000 if args.get("timeout_ms") else 120))
            from mana_agent.transactional_actions.adapters import ShellActionAdapter
            from mana_agent.transactional_actions.gateway import ApprovalRequired
            from mana_agent.transactional_actions.runtime import default_action_gateway
            from mana_agent.utils.shell_argv import local_shell_argv
            import subprocess
            working = (self.repo_root / str(cwd or ".")).resolve()
            if not working.is_relative_to(self.repo_root) or not working.is_dir():
                raise ValueError("Command cwd escapes the assigned workspace")
            action_runtime = default_action_gateway(self.repo_root)
            approval_id = str(args.get("action_approval_id") or "")
            operation_key = hashlib.sha256(json.dumps({"task_id": self.task_id,
                "call_id": args["_mana_call_id"], "command": cmd, "cwd": str(working)}, sort_keys=True).encode()).hexdigest()
            if approval_id:
                grant = action_runtime.approvals.get(approval_id)
                if grant:
                    approved_action = action_runtime.store.get_action(grant.action_id)
                    if approved_action.parent_task_id != (self.task_id or "internal-coding"):
                        raise ValueError("Command approval belongs to a different task")
                    operation_key = approved_action.idempotency_key
            adapter = ShellActionAdapter(
                argv=local_shell_argv(cmd), cwd=working, environment={},
                parent_task_id=self.task_id or "internal-coding", actor="user",
                originating_agent="internal_coding", policy_context={"tool": "shell"},
                idempotency_key=operation_key,
                timeout_seconds=timeout_s,
                expected_outputs=list(args.get("expected_outputs") or []),
                allow_command_result_verification=True,
                runner=lambda argv, **kwargs: subprocess.run(argv, cwd=working, capture_output=True,
                    text=True, timeout=timeout_s, check=False),
            )
            try:
                outcome = action_runtime.execute(adapter, approval_id=approval_id)
            except ApprovalRequired as pending:
                return {"ok": False, "awaiting_approval": True, "inbox_item_id": pending.inbox_item_id}
            return {"ok": outcome.action.state.value == "committed", **outcome.result,
                    "action_id": outcome.action.action_id}


        elif name == "conversation_context_read":
            from mana_agent.chat.history import get_history
            from mana_agent.tools.context_retrieval import execute_conversation_context_read
            query = args.get("query")
            max_turns = int(args.get("max_turns") or 5)
            max_tokens = int(args.get("max_tokens") or 2000)
            before_turn_id = args.get("before_turn_id")
            try:
                hist = get_history()
                res = execute_conversation_context_read(
                    session_id=getattr(hist, "session_id", "default_session"),
                    conversation_id=getattr(hist, "conversation_id", "default_conversation"),
                    authenticated_user_id="default_user",
                    history_store=hist,
                    query=query,
                    max_turns=max_turns,
                    max_tokens=max_tokens,
                    before_turn_id=before_turn_id,
                )
                return {"ok": True, "result": res}
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "CONTEXT_READ_FAILED"}

        elif name == "memory_read":
            from mana_agent.memory.capsules.service import CapsuleService
            from mana_agent.tools.context_retrieval import execute_memory_read
            query = str(args.get("query") or "")
            max_capsules = int(args.get("max_capsules") or 3)
            max_tokens = int(args.get("max_tokens") or 1000)
            tags = list(args.get("tags") or [])
            try:
                res = execute_memory_read(
                    capsule_service=CapsuleService(self.repo_root),
                    authenticated_user_id="default_user",
                    session_id="default_session",
                    repository_id=str(self.repo_root),
                    query=query,
                    max_capsules=max_capsules,
                    max_tokens=max_tokens,
                    tags=tags,
                )
                return {"ok": True, "result": res}
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "MEMORY_READ_FAILED"}

        elif name.startswith("email_"):
            from mana_agent.connectors.email.runtime_tools import build_email_tools
            try:
                tools = {t.name: t for t in build_email_tools()}
                if name in tools:
                    res = tools[name].invoke(args)
                    return json.loads(res) if isinstance(res, str) else {"ok": True, "result": res}
                return {"ok": False, "error": f"Email tool not found: {name}", "error_code": "UNKNOWN_TOOL"}
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "EMAIL_TOOL_ERROR"}

        elif name == "verify_project":
            res = verify_project(self.repo_root)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "git_status":
            res = git_status(self.repo_root)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "git_diff":
            path = str(args.get("path") or "")
            res = git_diff(self.repo_root, path=path)
            return json.loads(res) if isinstance(res, str) else res

        elif name == "git_log":
            from mana_agent.tools.repository import git_log
            limit = int(args.get("limit") or 10)
            res = git_log(self.repo_root, limit=limit)
            return json.loads(res) if isinstance(res, str) else res

        elif name.startswith("git_") or tool_name.startswith("git."):
            from mana_agent.multi_agent.tools.git_tools import execute_tool as execute_git_tool
            res = execute_git_tool(tool_name, args, repo_path=self.repo_root)
            return res if isinstance(res, dict) else (json.loads(res) if isinstance(res, str) else {"ok": True, "result": res})

        elif name.startswith("document_"):
            from mana_agent.documents.service import DocumentService
            from mana_agent.multi_agent.tools.tool_manager import ToolManager
            service = DocumentService(workspace_root=self.repo_root)
            mgr = ToolManager(workspace_root=self.repo_root)
            res = mgr._execute_document_tool(service, name, args)
            return res if isinstance(res, dict) else (json.loads(res) if isinstance(res, str) else {"ok": True, "result": res})

        elif name in {"web_search", "search"}:
            query = str(args.get("query") or "")
            try:
                from mana_agent.search.models import SearchDecision, SearchQuery
                from mana_agent.search.router import SearchConfig, SearchRouter
                config = SearchConfig.from_env()
                router = SearchRouter(root=str(self.repo_root), config=config)
                decision = SearchDecision(
                    needs_search=True,
                    targets=["web"],
                    reason="Model web search query",
                    confidence=0.9,
                    queries=[SearchQuery(query=query, target="web")],
                    max_results=config.max_results,
                    mode="web",
                )
                search_res = router.run(user_query=query, repo_context="", decision_override=decision)
                return {
                    "ok": True,
                    "results": [item.model_dump() if hasattr(item, "model_dump") else item for item in search_res.web_results],
                    "summary": search_res.context_block(),
                }
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "SEARCH_FAILED"}

        elif name == "semantic_search":
            query = str(args.get("query") or "")
            k = int(args.get("k") or 6)
            try:
                res = repo_search(self.repo_root, query=query, limit=k)
                return json.loads(res) if isinstance(res, str) else res
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "SEARCH_FAILED"}

        elif name in {"approval_request", "request_user_approval"}:
            from mana_agent.human_inbox.approval_tools import approval_request
            cmd = str(args.get("command") or args.get("cmd") or args.get("action") or "").strip()
            title = str(args.get("title") or (f"Approval required for command: {cmd}" if cmd else "User approval required"))
            reason = str(args.get("reason") or args.get("summary") or args.get("description") or "")
            inbox_item_id = str(args.get("inbox_item_id") or "").strip()
            action_id = str(args.get("action_id") or "").strip()
            risk_level = str(args.get("risk_level") or "medium")
            timeout_seconds = float(args.get("timeout_seconds") or 120.0)
            ws_root = args.get("workspace_root") or args.get("repo_path") or args.get("cwd") or self.repo_root

            if not cmd and not inbox_item_id and not action_id:
                cmd = title or reason or "approval_action"

            try:
                res = approval_request(
                    command=cmd,
                    title=title,
                    reason=reason,
                    inbox_item_id=inbox_item_id,
                    action_id=action_id,
                    risk_level=risk_level,
                    timeout_seconds=timeout_seconds,
                    workspace_root=ws_root,
                )
                if isinstance(res, dict):
                    if "ok" not in res:
                        res["ok"] = bool(res.get("approved", True))
                    return res
                return {"ok": True, "result": res}
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "APPROVAL_REQUEST_FAILED"}

        elif name == "wait_for_approval":
            from mana_agent.human_inbox.approval_tools import wait_for_approval
            try:
                res = wait_for_approval(
                    inbox_item_id=str(args.get("inbox_item_id") or ""),
                    source_decision_id=str(args.get("source_decision_id") or "decision_wait"),
                    task_id=str(args.get("task_id") or "task_wait"),
                    agent_id=str(args.get("agent_id") or "ask_agent"),
                    timeout_seconds=float(args.get("timeout_seconds") or 300.0),
                    poll_interval_seconds=float(args.get("poll_interval_seconds") or 0.25),
                )
                res_dict = dict(res) if hasattr(res, "items") else {"ok": True, "result": res}
                if "ok" not in res_dict:
                    res_dict["ok"] = bool(res_dict.get("may_continue", True))
                return res_dict
            except Exception as exc:
                return {"ok": False, "error": str(exc), "error_code": "WAIT_FOR_APPROVAL_FAILED"}

        elif name in {"batch_create_job", "batch_submit_requests"}:
            from mana_agent.batch.tools import batch_create_job
            reqs = args.get("requests")
            if reqs is None:
                reqs = [args]
            target_model = str(args.get("model") or self.model or "").strip()
            target_task_id = str(args.get("task_id") or self.task_id or "").strip()
            target_provider = str(args.get("provider") or self.provider or "openai").strip()
            return batch_create_job(
                requests=reqs,
                endpoint=str(args.get("endpoint") or "/v1/responses"),
                completion_window=str(args.get("completion_window") or "24h"),
                model=target_model,
                task_id=target_task_id,
                idempotency_key=str(args.get("idempotency_key") or ""),
                metadata=args.get("metadata") if isinstance(args.get("metadata"), dict) else None,
                mode=str(args.get("mode") or "auto"),
                provider=target_provider,
            )

        elif name in {"batch_get_status", "batch_check_status"}:
            from mana_agent.batch.tools import batch_get_status
            return batch_get_status(batch_id=str(args.get("batch_id") or ""))

        elif name == "batch_list_jobs":
            from mana_agent.batch.tools import batch_list_jobs
            return batch_list_jobs(
                limit=int(args.get("limit") or 20),
                status=str(args.get("status") or ""),
                task_id=str(args.get("task_id") or ""),
                sync_platform=bool(args.get("sync_platform", False)),
            )

        elif name == "batch_cancel_job":
            from mana_agent.batch.tools import batch_cancel_job
            return batch_cancel_job(batch_id=str(args.get("batch_id") or ""))

        elif name in {"batch_download_results", "batch_retrieve_results"}:
            from mana_agent.batch.tools import batch_download_results
            return batch_download_results(batch_id=str(args.get("batch_id") or ""))

        return {"ok": False, "error": f"Unknown tool: {tool_name}", "error_code": "UNKNOWN_TOOL"}


def build_programmatic_tool_definitions(
    *,
    allowed_callers: Sequence[str] = ("direct", "programmatic"),
    contracts: list[ToolContract] | None = None,
) -> list[dict[str, Any]]:
    """Build OpenAI-compatible tool schemas including the programmatic_tool_calling host tool."""
    tool_defs: list[dict[str, Any]] = [
        {"type": "programmatic_tool_calling"}
    ]

    seen_names: set[str] = set()
    resolved_contracts = contracts or coding_tool_contracts()
    for contract in resolved_contracts:
        tool_name = re.sub(r"[^a-zA-Z0-9_-]", "_", contract.name)
        if tool_name in seen_names:
            continue
        seen_names.add(tool_name)
        tool_entry: dict[str, Any] = {
            "type": "function",
            "name": tool_name,
            "description": contract.description,
            "parameters": contract.input_schema,
            "allowed_callers": list(allowed_callers),
        }
        if contract.output_schema:
            tool_entry["output_schema"] = contract.output_schema
        tool_defs.append(tool_entry)

    return tool_defs


class ProgrammaticExecutionSession:
    """Manages the full request/response continuation lifecycle for Programmatic Tool Calling."""

    def __init__(
        self,
        *,
        task_id: str,
        dispatcher: ToolExecutionDispatcher,
        max_tool_calls: int = 50,
        backend_name: str = "internal",
    ) -> None:
        self.task_id = task_id
        self.dispatcher = dispatcher
        self.backend_name = backend_name
        self.state = ProgrammaticExecutionState(
            task_id=task_id,
            max_tool_calls=max_tool_calls,
        )
        self._sequence = 0

    def _next_sequence(self) -> int:
        self._sequence += 1
        return self._sequence

    def handle_program_item(self, item: dict[str, Any]) -> None:
        """Handle incoming 'program' item from OpenAI Responses API."""
        program_id = str(item.get("call_id") or item.get("id") or "")
        code = str(item.get("code") or "")
        self.state.program_id = program_id
        self.state.program_code = code

        publish_coding_event(AgentEvent(
            event_type="program.started",
            task_id=self.task_id,
            backend=self.backend_name,
            sequence=self._next_sequence(),
            title="Generated JavaScript Program Execution",
            summary=f"Executing {len(code.splitlines())} lines of generated tool orchestration code",
            visibility="progress",
            semantic_kind="program_execution",
            payload={"call_id": program_id, "code_preview": code[:2000]},
        ))

    def handle_function_call(self, item: dict[str, Any]) -> dict[str, Any]:
        """Execute client-side function call requested by the running program and format function_call_output."""
        call_id = str(item.get("call_id") or "")
        tool_name = str(item.get("name") or "")
        raw_args = item.get("arguments", {})
        if isinstance(raw_args, str):
            try:
                arguments = json.loads(raw_args)
            except Exception:
                arguments = {"raw": raw_args}
        else:
            arguments = dict(raw_args)

        caller = item.get("caller")
        caller_prog_id = str(caller.get("call_id") or "") if isinstance(caller, dict) else None

        if self.state.tool_calls_executed >= self.state.max_tool_calls:
            err_msg = f"Maximum tool calls budget ({self.state.max_tool_calls}) exceeded for program"
            self.state.errors.append(err_msg)
            return {
                "type": "function_call_output",
                "call_id": call_id,
                "output": json.dumps({"ok": False, "error": err_msg, "error_code": "BUDGET_EXCEEDED"}),
            }

        self.state.tool_calls_executed += 1

        try:
            from mana_agent.commands.ui_helpers import emit_tool_event
            emit_tool_event(
                "start",
                tool_name,
                args=json.dumps(arguments, ensure_ascii=False, default=str),
                event_id=call_id,
            )
        except Exception:
            pass

        logger.info("› Tool call [%s]: %s (args=%s)", call_id, tool_name, arguments)

        publish_coding_event(AgentEvent(
            event_type="tool.call.started",
            task_id=self.task_id,
            backend=self.backend_name,
            sequence=self._next_sequence(),
            title=f"Tool call: {tool_name}",
            tool_name=tool_name,
            visibility="progress",
            semantic_kind="tool_execution",
            payload={"call_id": call_id, "arguments": arguments, "caller": caller},
        ))

        t0 = time.perf_counter()
        result = self.dispatcher.dispatch(tool_name, arguments, call_id=call_id)
        duration_ms = int((time.perf_counter() - t0) * 1000)
        if result.get("ok") and tool_name in {"write_file", "create_file", "edit_file", "multi_edit_file", "delete_file",
                "apply_patch", "apply_patch_batch", "batch_apply_patches", "batch_write_files", "batch_move_files", "batch_delete_files"}:
            self.state.verification_results.clear()
        if tool_name in {"verify_project", "run_command", "run_script_once", "shell"}:
            self.state.verification_results.append({"tool": tool_name, "arguments": arguments, "result": result})

        # Track mutations and commands
        if result.get("ok"):
            if tool_name in {"write_file", "create_file", "edit_file", "multi_edit_file", "delete_file"}:
                changed_path = str(arguments.get("path") or "")
                if changed_path and changed_path not in self.state.changed_files:
                    self.state.changed_files.append(changed_path)
            elif tool_name in {"apply_patch", "apply_patch_batch", "batch_apply_patches", "batch_write_files", "batch_move_files"}:
                touched = result.get("touched_files") or result.get("changed_files") or result.get("files_changed") or []
                for p in touched:
                    if p not in self.state.changed_files:
                        self.state.changed_files.append(str(p))
            elif tool_name == "batch_delete_files":
                deleted = result.get("deleted_files") or []
                for p in deleted:
                    if p not in self.state.changed_files:
                        self.state.changed_files.append(str(p))
            elif tool_name in {"run_command", "run_script_once", "shell"}:
                cmd = str(arguments.get("command") or arguments.get("script") or "")
                if cmd:
                    self.state.commands_run.append(cmd)

        status = "success" if result.get("ok", True) else "failed"

        try:
            from mana_agent.commands.ui_helpers import emit_tool_event
            if status == "success":
                emit_tool_event("end", tool_name, duration=duration_ms / 1000.0, event_id=call_id)
            else:
                emit_tool_event("error", tool_name, duration=duration_ms / 1000.0, error=str(result.get("error") or ""), event_id=call_id)
        except Exception:
            pass

        logger.info(
            "✓ Tool finished [%s]: %s (status=%s, duration=%dms)",
            call_id,
            tool_name,
            status,
            duration_ms,
        )

        publish_coding_event(AgentEvent(
            event_type="tool.call.completed" if status == "success" else "tool.call.failed",
            task_id=self.task_id,
            backend=self.backend_name,
            sequence=self._next_sequence(),
            status="success" if status == "success" else "failed",
            title=f"Tool call: {tool_name} ({status})",
            tool_name=tool_name,
            duration_ms=duration_ms,
            visibility="progress",
            semantic_kind="tool_execution",
            error=str(result.get("error") or ""),
            output_preview=str(result.get("content") or result.get("stdout") or result)[:500],
            payload={"call_id": call_id, "result": result},
        ))

        output_json = json.dumps(result, ensure_ascii=False)
        return {
            "type": "function_call_output",
            "call_id": call_id,
            "output": output_json,
        }

    def handle_program_output(self, item: dict[str, Any]) -> None:
        """Handle incoming 'program_output' item when JS execution completes."""
        output = item.get("output")
        publish_coding_event(AgentEvent(
            event_type="program.completed",
            task_id=self.task_id,
            backend=self.backend_name,
            sequence=self._next_sequence(),
            status="success",
            title="Programmatic Execution Completed",
            summary=f"Completed {self.state.tool_calls_executed} tool call(s)",
            visibility="progress",
            semantic_kind="program_execution",
            payload={"output": output},
        ))


